    """When the file carries no recognizable section markers but the DB flag
    says Q&A is present, treat the entire file as Q&A (don't lose content)."""
    text = "Just some text without markers. Brian: question. Mgmt: answer."
    prepared, qa = _split_transcript_sections(text, has_qa_flag=True)
    assert prepared is None
    assert qa is not None and "Brian" in qa


