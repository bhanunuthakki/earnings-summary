def _seed_transcripts_dir(repo_root: Path, ticker: str, quarters: list[tuple[int, int, str]]) -> None:
    """Write transcripts/processed/<TICKER>_Q<n>_<Y>.txt files with given content."""
    d = repo_root / "transcripts" / "processed"
    d.mkdir(parents=True, exist_ok=True)
    for q, y, content in quarters:
        (d / f"{ticker}_Q{q}_{y}.txt").write_text(content, encoding="utf-8")


def _seed_transcripts_db(repo_root: Path, ticker: str, rows: list[tuple[int, int, bool | None]]) -> None:
    """Seed a minimal portfolio.db with transcripts rows carrying has_qa_section flags.

    Also creates an empty `earnings_surprises` table so the §6 surprise-card
    builder (which fires unconditionally inside `build`) doesn't error out
    on a missing table — it tolerates an empty result set but not a missing
    schema.
    """
    db_dir = repo_root / "data"
    db_dir.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_dir / "portfolio.db")
    conn.executescript(
        """
        CREATE TABLE IF NOT EXISTS transcripts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            document_id INTEGER,
            ticker TEXT NOT NULL,
            call_date TEXT,
            fiscal_period_type TEXT NOT NULL,
            period_end TEXT NOT NULL,
            source_url TEXT,
            has_qa_section INTEGER
        );
        CREATE TABLE IF NOT EXISTS earnings_surprises (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            ticker TEXT NOT NULL,
            release_date TEXT NOT NULL,
            eps_surprise_pct NUMERIC,
            revenue_surprise_pct NUMERIC,
            source_name TEXT NOT NULL,
            fetched_at TEXT NOT NULL
        );
        """
    )
    for q, y, flag in rows:
        # period_end's year prefix is what _load_has_qa_flags matches against
        pe = f"{y}-{3 * q:02d}-30"
        conn.execute(
            "INSERT INTO transcripts (ticker, fiscal_period_type, period_end, has_qa_section) "
            "VALUES (?, ?, ?, ?)",
            (ticker, f"Q{q}", pe, None if flag is None else int(flag)),
        )
    conn.commit()
    conn.close()


def _aggregator_qa(period: str, body: str) -> str:
    return (
        f"=== SYNTHESIZED QUARTERLY UPDATE — Q&A SEGMENT ONLY ===\n"
        f"Period: {period}\n\n=== Q&A SEGMENT ===\n{body}\n"
    )


def _callstreet_full(prepared: str, qa: str) -> str:
    return (
        f"MANAGEMENT DISCUSSION SECTION\n\n{prepared}\n\n"
        f"QUESTION AND ANSWER SECTION\n\n{qa}\n"
    )


def _mock_themes_response(prepared: list[dict[str, Any]], qa: list[dict[str, Any]]) -> str:
    return json.dumps({"prepared_themes": prepared, "qa_themes": qa})


def test_build_themes_mixed_qa_flags_populates_both_sides(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    ticker = "ACME"
    # Two aggregator (Q&A-only) + two CallStreet-full transcripts in the 4Q window.
    _seed_transcripts_dir(
        repo,
        ticker,
        [
            (2, 2025, _aggregator_qa("Q2 2025", "B Brian: question about cloud.")),
            (3, 2025, _aggregator_qa("Q3 2025", "B Brian: another cloud question.")),
            (4, 2025, _callstreet_full(
                "Operator: welcome. CEO: revenue grew 20%, margins expanded.",
                "Analyst: TPU pricing? CFO: opportunistic."
            )),
            (1, 2026, _callstreet_full(
                "CEO: Q1 was strong, GCP up 35%.",
                "Analyst: Capex 2027? Anat: it will increase significantly."
            )),
        ],
    )
    _seed_transcripts_db(
        repo,
        ticker,
        [
            (2, 2025, True),
            (3, 2025, True),
            (4, 2025, True),
            (1, 2026, True),
        ],
    )

    called_with: dict[str, Any] = {}

    def fake_extractor(ticker_arg: str, transcripts_arg: list[dict[str, Any]]) -> str:
        called_with["ticker"] = ticker_arg
        called_with["transcripts"] = transcripts_arg
        return _mock_themes_response(
            prepared=[
                {
                    "theme_name": "Margin expansion narrative",
                    "mentions_per_quarter": {"Q4 2025": 1, "Q1 2026": 1},
                    "evidence": [
                        {"period": "Q4 2025", "speaker": "CEO", "text": "Margins expanded."}
                    ],
                }
            ],
            qa=[
                {
                    "theme_name": "Capex trajectory",
                    "mentions_per_quarter": {"Q1 2026": 1, "Q4 2025": 1},
                    "evidence": [
                        {"period": "Q1 2026", "speaker": "Analyst", "text": "Capex 2027?"}
                    ],
                }
            ],
        )

    # The builder imports lazily — patch on the llm_client module instead.
    import llm_client

    monkeypatch.setattr(llm_client, "extract_qa_vs_prepared_themes", fake_extractor)

    section = build(ticker, repo, enable_llm=True)

    assert called_with["ticker"] == ticker
    # 4 transcripts in the window, all surfaced to the extractor
    assert len(called_with["transcripts"]) == 4
    # Aggregator quarters carry prepared=None, qa=text
    aggregator_entries = [t for t in called_with["transcripts"] if t["prepared"] is None]
    assert len(aggregator_entries) == 2
    # CallStreet quarters carry both sides
    full_entries = [t for t in called_with["transcripts"] if t["prepared"] and t["qa"]]
    assert len(full_entries) == 2

    assert len(section.prepared_remarks_themes) == 1
    assert section.prepared_remarks_themes[0].theme_name == "Margin expansion narrative"
    assert len(section.qa_themes) == 1
    assert section.qa_themes[0].theme_name == "Capex trajectory"
    # No fallback note when both sides have content
    assert section.themes_note is None


def test_build_themes_no_qa_falls_back_to_prepared_only_with_note(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    ticker = "PREP"
    # All 4 transcripts are prepared-remarks only (no Q&A in any of them).
    # has_qa_section = False on every row.
    _seed_transcripts_dir(
        repo,
        ticker,
        [
            (2, 2025, "Operator: welcome. CEO: revenue grew 20%."),
            (3, 2025, "Operator: welcome. CEO: Q3 was strong."),
            (4, 2025, "Operator: welcome. CEO: Margins expanded."),
            (1, 2026, "Operator: welcome. CEO: Q1 print was good."),
        ],
    )
    _seed_transcripts_db(
        repo,
        ticker,
        [
            (2, 2025, False),
            (3, 2025, False),
            (4, 2025, False),
            (1, 2026, False),
        ],
    )

    def fake_extractor(ticker_arg: str, transcripts_arg: list[dict[str, Any]]) -> str:
        # Verify the extractor sees prepared on every entry, qa nowhere
        assert all(t["prepared"] for t in transcripts_arg)
        assert all(t["qa"] is None for t in transcripts_arg)
        return _mock_themes_response(
            prepared=[
                {
                    "theme_name": "Top-line growth framing",
                    "mentions_per_quarter": {"Q2 2025": 1, "Q4 2025": 1},
                    "evidence": [],
                }
            ],
            qa=[],  # well-behaved LLM returns empty for the missing side
        )

    import llm_client

    monkeypatch.setattr(llm_client, "extract_qa_vs_prepared_themes", fake_extractor)

    section = build(ticker, repo, enable_llm=True)

    assert section.prepared_remarks_themes
    assert section.qa_themes == []
    assert section.themes_note is not None
    assert "Q&A" in section.themes_note


def test_build_themes_defensively_drops_qa_themes_when_no_source_qa(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """If the LLM ignores the empty-side instruction and returns qa themes
    anyway, the builder forces them to [] because we know there was no
    source material to ground them in."""
    repo = tmp_path / "repo"
    repo.mkdir()
    ticker = "STRICT"
    _seed_transcripts_dir(repo, ticker, [(1, 2026, "Operator: welcome. CEO: Q1 was good.")])
    _seed_transcripts_db(repo, ticker, [(1, 2026, False)])

    def fake_extractor(_t: str, _x: list[dict[str, Any]]) -> str:
        return _mock_themes_response(
            prepared=[
                {"theme_name": "P", "mentions_per_quarter": {"Q1 2026": 1}, "evidence": []}
            ],
            qa=[
                {"theme_name": "Made-up QA theme", "mentions_per_quarter": {"Q1 2026": 1}, "evidence": []}
            ],
        )

    import llm_client

    monkeypatch.setattr(llm_client, "extract_qa_vs_prepared_themes", fake_extractor)

    section = build(ticker, repo, enable_llm=True)
    assert section.prepared_remarks_themes
    assert section.qa_themes == [], "qa themes must be force-dropped when no Q&A source material exists"


