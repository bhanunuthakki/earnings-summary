"""Tests for §5 Earnings — cross-quarter themes split (prepared vs Q&A).

Covers:
  - the transcript splitter's detection ladder (aggregator banner, CallStreet
    header, has_qa_section fallback)
  - the LLM-response parser (well-formed JSON, fence-stripped JSON, malformed)
  - the builder end-to-end with mocked LLM:
      * mixed has_qa_section flags → both sides populate
      * no Q&A across the window → fallback note + prepared-only
      * no prepared across the window → fallback note + Q&A-only
  - the markdown + HTML renderers' theme blocks

Mocking strategy: the LLM call goes through llm_client.extract_qa_vs_prepared_themes,
which we monkeypatch on the EARNINGS section's import name (it imports the
function lazily inside _build_themes) so the test doesn't need a real Claude CLI.
"""

