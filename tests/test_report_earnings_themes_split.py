def test_parse_themes_response_well_formed() -> None:
    raw = json.dumps(
        {
            "prepared_themes": [
                {
                    "theme_name": "CapEx trajectory",
                    "mentions_per_quarter": {"Q4 2025": 2, "Q1 2026": 3},
                    "evidence": [
                        {"period": "Q1 2026", "speaker": "Anat", "text": "CapEx will increase significantly."}
                    ],
                }
            ],
            "qa_themes": [
                {
                    "theme_name": "AI compute capacity",
                    "mentions_per_quarter": {"Q1 2026": 4},
                    "evidence": [
                        {"period": "Q1 2026", "speaker": "Brian (MS)", "text": "Help us think about TPUs."}
                    ],
                }
            ],
        }
    )
    prepared, qa = _parse_themes_response(raw)
    assert len(prepared) == 1
    assert prepared[0].theme_name == "CapEx trajectory"
    assert prepared[0].mentions_per_quarter == {"Q4 2025": 2, "Q1 2026": 3}
    # last_4q_count derived from sum when LLM omits it
    assert prepared[0].last_4q_count == 5
    assert prepared[0].evidence[0].speaker == "Anat"
    assert len(qa) == 1
    assert qa[0].theme_name == "AI compute capacity"


