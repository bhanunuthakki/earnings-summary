def test_build_themes_uses_cache_on_second_call(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    ticker = "CACHE"
    _seed_transcripts_dir(repo, ticker, [(1, 2026, _aggregator_qa("Q1 2026", "B: question."))])
    _seed_transcripts_db(repo, ticker, [(1, 2026, True)])

    call_count = {"n": 0}

    def fake_extractor(_t: str, _x: list[dict[str, Any]]) -> str:
        call_count["n"] += 1
        return _mock_themes_response(
            prepared=[],
            qa=[
                {"theme_name": "Question shape", "mentions_per_quarter": {"Q1 2026": 1}, "evidence": []}
            ],
        )

    import llm_client

    monkeypatch.setattr(llm_client, "extract_qa_vs_prepared_themes", fake_extractor)

    section1 = build(ticker, repo, enable_llm=True)
    section2 = build(ticker, repo, enable_llm=True)
    assert call_count["n"] == 1, "second build should hit the on-disk cache"
    assert section1.qa_themes[0].theme_name == section2.qa_themes[0].theme_name
    # Cache file is the source-of-truth on disk
    assert (repo / "data" / "earnings_themes" / "CACHE.json").exists()


