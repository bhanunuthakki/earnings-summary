# FMP snapshot
# ---------------------------------------------------------------------------


FMP_ENDPOINTS = (
    ("income-statement", "Income Statement"),
    ("balance-sheet-statement", "Balance Sheet"),
    ("cash-flow-statement", "Cash Flow"),
    ("key-metrics", "Key Metrics"),
    ("ratios", "Ratios"),
)


def _fmp_get(endpoint: str, ticker: str, period: FmpPeriod, limit: int = 16) -> list[dict[str, Any]]:
    if not FMP_API_KEY:
        raise RuntimeError("FMP_API_KEY missing from environment")
    url = f"{FMP_BASE}/{endpoint}"
    resp = requests.get(
        url,
        params={
            "symbol": ticker,
            "period": period.value,
            "limit": limit,
            "apikey": FMP_API_KEY,
        },
        timeout=REQUESTS_TIMEOUT,
    )
    if resp.status_code in (401, 403):
        raise RuntimeError(f"FMP auth error {resp.status_code} for {endpoint}: {resp.text[:200]}")
    resp.raise_for_status()
    payload = resp.json()
    if not isinstance(payload, list):
        raise RuntimeError(f"FMP {endpoint} returned non-list payload")
    return payload


def _pick_period_record(
    records: list[dict[str, Any]],
    year: int,
    quarter: int,
    period_end_hint: str | None,
) -> dict[str, Any] | None:
    if not records:
        return None
    if period_end_hint:
        for r in records:
            if r.get("date") == period_end_hint:
                return r
    target = f"Q{quarter}"
    for r in records:
        if str(r.get("calendarYear")) == str(year) and r.get("period") == target:
            return r
    return None


def fetch_fmp_snapshot(spec: SynthInput) -> Section | None:
    canonical = resolve_ticker(spec.ticker)
    if not FMP_API_KEY:
        print("[warn] FMP_API_KEY not set — skipping FMP snapshot", file=sys.stderr)
        return None

    blocks: list[str] = []
    matched_period_end: str | None = None
    for endpoint, label in FMP_ENDPOINTS:
        records = _fmp_get(endpoint, canonical, FmpPeriod.QUARTER, limit=16)
        record = _pick_period_record(records, spec.year, spec.quarter, spec.fmp_period_end_hint)
        if record is None:
            blocks.append(f"-- {label}: no record matched ({canonical} Q{spec.quarter} {spec.year})\n")
            continue
        matched_period_end = record.get("date") or matched_period_end
        blocks.append(
            f"-- {label} (period_end={record.get('date')}, currency={record.get('reportedCurrency')}) --\n"
            + json.dumps(record, indent=2, default=str)
            + "\n"
        )

    body = "\n".join(blocks).strip()
    if not body:
        return None
    return Section(
        title=f"FMP FINANCIAL SNAPSHOT (period_end={matched_period_end or 'unknown'})",
        body=body,
        source_label=f"FMP /stable/ quarterly statements for {canonical}",
    )


# ---------------------------------------------------------------------------
# External recaps
# ---------------------------------------------------------------------------


def fetch_recaps(spec: SynthInput) -> list[Section]:
    sections: list[Section] = []
    for url in spec.recap_urls:
        url_str = str(url)
        text = _extract_main_text_from_html(_http_get(url_str))
        if not text:
            print(f"[warn] recap URL produced no text: {url_str}", file=sys.stderr)
            continue
        sections.append(
            Section(
                title="EXTERNAL RECAP / DISTILLATION",
                body=text,
                source_label=url_str,
            )
        )
    return sections


