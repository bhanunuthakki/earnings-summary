def main() -> None:
    parser = argparse.ArgumentParser(description="Synthesize a quarterly text-update transcript when no audio is available.")
    parser.add_argument("--ticker", required=True)
    parser.add_argument("--year", type=int, required=True)
    parser.add_argument("--quarter", type=int, choices=[1, 2, 3, 4], required=True)
    parser.add_argument("--press-release-url")
    parser.add_argument("--press-release-pdf", type=Path)
    parser.add_argument("--press-release-text",
                        help="Manual paste fallback when URL/PDF aren't available.")
    parser.add_argument("--recap-url", action="append", default=[],
                        help="External recap URL; pass multiple times for multiple sources.")
    parser.add_argument("--ir-pdf", action="append", default=[], type=Path,
                        help="Path to an IR PDF (investor letter, deck, supplemental). Repeatable.")
    parser.add_argument("--no-auto-ir", action="store_true",
                        help="Disable auto-scan of micro_thesis/sources/<TICKER>/ for matching IR PDFs.")
    parser.add_argument("--fmp-period-end",
                        help="Exact FMP period_end date (YYYY-MM-DD) if calendarYear/period match is unreliable.")
    parser.add_argument("--force", action="store_true",
                        help="Overwrite an existing transcript file.")
    args = parser.parse_args()

    spec = SynthInput(
        ticker=args.ticker,
        year=args.year,
        quarter=args.quarter,
        press_release_url=args.press_release_url,
        press_release_pdf=args.press_release_pdf,
        press_release_text=args.press_release_text,
        recap_urls=args.recap_url,
        ir_pdfs=args.ir_pdf,
        auto_ir_scan=not args.no_auto_ir,
        fmp_period_end_hint=args.fmp_period_end,
    )
    synthesize(spec, force=args.force)


if __name__ == "__main__":
    main()
