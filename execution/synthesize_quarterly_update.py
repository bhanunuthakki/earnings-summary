# Assembly
# ---------------------------------------------------------------------------


def _build_header(spec: SynthInput, sections: list[Section]) -> str:
    canonical = resolve_ticker(spec.ticker)
    now = _dt.datetime.now().isoformat(timespec="seconds")
    lines = [
        SYNTH_BANNER,
        f"Ticker:   {canonical}",
        f"Period:   Q{spec.quarter} {spec.year}",
        f"Built at: {now}",
        "Sources:",
    ]
    for s in sections:
        lines.append(f"  - {s.title} ← {s.source_label}")
    lines.append("")
    return "\n".join(lines)


def _render(sections: list[Section]) -> str:
    parts: list[str] = []
    for s in sections:
        parts.append(f"\n=== {s.title} ===")
        parts.append(f"[source: {s.source_label}]")
        parts.append(s.body)
    return "\n".join(parts).strip() + "\n"


def synthesize(spec: SynthInput, force: bool = False) -> SynthResult:
    canonical = resolve_ticker(spec.ticker)
    qlabel = f"Q{spec.quarter}"
    output_path = RAW_DIR / f"{canonical}_{qlabel}_{spec.year}.txt"

    if (index_manager.has_transcript(canonical, spec.year, qlabel) or output_path.exists()):
        if not force:
            raise FileExistsError(
                f"transcript already present at {output_path}; "
                f"pass --force to overwrite"
            )
        if output_path.exists():
            output_path.unlink()

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    TMP_DIR.mkdir(parents=True, exist_ok=True)

    sections: list[Section] = []
    pr = fetch_press_release(spec)
    if pr is not None:
        sections.append(pr)
    sections.extend(ir_doc_sections(spec))
    snap = fetch_fmp_snapshot(spec)
    if snap is not None:
        sections.append(snap)
    sections.extend(fetch_recaps(spec))

    if not sections:
        raise RuntimeError(
            "no sections produced — pass at least one of "
            "--press-release-url / --press-release-pdf / --press-release-text / "
            "--ir-pdf / --recap-url (or rely on auto IR scan in micro_thesis/sources/)"
        )

    output_path.write_text(_build_header(spec, sections) + _render(sections), encoding="utf-8")

    qa_result = validate_synthesized_transcript(output_path)
    index_manager.register_transcript(
        canonical,
        spec.year,
        qlabel,
        source="synthesized_text",
        filepath=output_path.name,
        has_qa=False,  # press releases / recaps don't carry a Q&A segment
        qa_status=qa_result.status.value,
        qa_details=qa_result.model_dump(mode="json"),
    )
    if qa_result.status == QaStatus.OK:
        print(f"[done] {output_path} ({len(sections)} sections) qa=ok")
    else:
        print(
            f"[done-qa-failed] {output_path} ({len(sections)} sections) "
            f"qa=failed issues={len(qa_result.issues)}"
        )
        for issue in qa_result.issues:
            print(f"      - {issue}")
    return SynthResult(
        ticker=canonical,
        year=spec.year,
        quarter=spec.quarter,
        output_path=output_path,
        sections_written=len(sections),
    )


